import fs from 'node:fs';
export function buildCatalog() {
  const bank = JSON.parse(fs.readFileSync('public/data/problems.json', 'utf8'));
  const coverage = JSON.parse(fs.readFileSync('public/data/coverage.json', 'utf8'));
  const rows = new Map(bank.map(p => {
    if (!p.id || !Number.isFinite(p.difficulty) || p.difficulty < 1 || p.difficulty > 10) throw Error('Invalid leaderboard question');
    return [p.id, { canonical: p.id, difficulty: Math.round(p.difficulty * 10) }];
  }));
  const aliases = Object.fromEntries((coverage.confirmedMerges || []).map(m => [m.merge, m.keep]));
  for (const id of Object.keys(aliases)) {
    let target = aliases[id]; const seen = new Set([id]);
    while (aliases[target]) { if (seen.has(target)) throw Error('Cyclic question alias'); seen.add(target); target = aliases[target]; }
    if (!rows.has(target)) throw Error('Unknown canonical question: ' + target);
    aliases[id] = target; rows.set(id, rows.get(target));
  }
  const quote = value => "'" + value.replaceAll("'", "''") + "'";
  const lines = ['-- Generated by scripts/build-leaderboard-catalog.mjs. Refresh after bank changes.', 'DELETE FROM atlas_question_catalog;'];
  const entries = [...rows];
  for (let i = 0; i < entries.length; i += 100) lines.push('INSERT INTO atlas_question_catalog (problem_id, canonical_id, difficulty_tenths) VALUES\n' + entries.slice(i, i + 100).map(([id, p]) => `(${quote(id)},${quote(p.canonical)},${p.difficulty})`).join(',\n') + ';');
  return { sql: lines.join('\n') + '\n', aliases: '// Generated from the confirmed question merges.\nexport const questionAliases = ' + JSON.stringify(aliases, null, 2) + ';\n' };
}
const output = buildCatalog();
if (process.argv.includes('--check')) {
  for (const [file, content] of [['cloudflare/leaderboard-catalog.sql', output.sql], ['server/question-aliases.mjs', output.aliases]]) if (fs.readFileSync(file, 'utf8') !== content) throw Error('Refresh the leaderboard catalog: node scripts/build-leaderboard-catalog.mjs');
} else {
  fs.writeFileSync('cloudflare/leaderboard-catalog.sql', output.sql);
  fs.writeFileSync('server/question-aliases.mjs', output.aliases);
}
